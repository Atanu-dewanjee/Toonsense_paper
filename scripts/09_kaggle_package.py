"""Step 9: package ToonSense as a self-contained Kaggle GPU job (one kernel per dataset).

    python scripts/09_kaggle_package.py --dataset banglaabusememe --user <kaggle-username>

writes kaggle/<dataset>/{run.py, kernel-metadata.json}. run.py embeds the code as a base64 tarball, downloads the
dataset inside the Kaggle session, runs steps 01-07 on GPU and leaves results in /kaggle/working/toonsense/.
Push with:   kaggle kernels push -p kaggle/<dataset>
Fetch with:  kaggle kernels output <user>/toonsense-<dataset> -p kaggle_output/<dataset>
"""
from __future__ import annotations

import argparse
import base64
import io
import json
import tarfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
INCLUDE = ["src", "scripts", "configs", "tests", "requirements.txt", "README.md", "ARCHITECTURE.md"]

