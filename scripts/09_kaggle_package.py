RUNNER = r'''# Auto-generated by scripts/09_kaggle_package.py — ToonSense on Kaggle GPU ({dataset})
import base64, io, os, subprocess, sys, tarfile, time

DATASET = {dataset!r}
CODE_B64 = {code!r}
DATA_CMDS = {cmds!r}
LABELS = {labels!r}
IMAGE_DIRS = {image_dirs!r}
STEPS = {steps!r}
REUSE = {reuse!r}  # copy features/ from an attached earlier ToonSense kernel output
DEVICE = {device!r}

W = "/kaggle/working/toonsense"
os.makedirs(W, exist_ok=True)
tarfile.open(fileobj=io.BytesIO(base64.b64decode(CODE_B64)), mode="r:gz").extractall(W)
os.makedirs(f"{{W}}/logs", exist_ok=True)


def sh(cmd):
    print("$", cmd, flush=True)
    subprocess.run(cmd, shell=True, check=True)


sh("pip install -q easyocr gdown openpyxl 2>&1 | tail -n 2")
os.makedirs("/tmp/data", exist_ok=True)
for c in DATA_CMDS:
    sh(c)

import yaml  # noqa: E402

cfg = yaml.safe_load(open(f"{{W}}/configs/default.yaml", encoding="utf-8"))
cfg["dataset"] = DATASET
cfg["datasets"][DATASET]["labels"] = LABELS
cfg["datasets"][DATASET]["image_dirs"] = IMAGE_DIRS
cfg["paths"]["hf_cache"] = "/tmp/hf"
cfg["paths"]["easyocr_cache"] = "/tmp/easyocr"
cfg["device"] = DEVICE
yaml.safe_dump(cfg, open(f"{{W}}/configs/kaggle.yaml", "w", encoding="utf-8"), allow_unicode=True, sort_keys=False)

if REUSE:
    import glob, shutil  # noqa: E401
    hits = sorted(glob.glob(f"/kaggle/input/**/toonsense/features/{{DATASET}}", recursive=True))
    print("reusing features from", hits, flush=True)
    if not hits:
        sys.exit("attached kernel output with toonsense/features not found under /kaggle/input")
    shutil.copytree(hits[0], f"{{W}}/features/{{DATASET}}", dirs_exist_ok=True)

import torch  # noqa: E402

print("CUDA:", torch.cuda.is_available(), torch.cuda.get_device_name(0) if torch.cuda.is_available() else "-", flush=True)
env = dict(os.environ, TOONSENSE_DATASET=DATASET, PYTHONIOENCODING="utf-8")
for step in STEPS:  # noqa
    t0 = time.time()
    log = f"{{W}}/logs/{{step.split()[0].replace('.py', '')}}.log"
    print(f"=== {{step}}", flush=True)
    with open(log, "w", encoding="utf-8") as fh:
        p = subprocess.Popen(f"python -u -W ignore scripts/{{step}} --config configs/kaggle.yaml", shell=True, cwd=W,
                             env=env, stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True, encoding="utf-8")
        for line in p.stdout:
            fh.write(line)
            if any(k in line for k in ("finished", "done", "Traceback", "Error", "wrote", "===", "variants")):
                print(line.rstrip(), flush=True)
        rc = p.wait()
    print(f"=== {{step}} exit={{rc}} in {{(time.time() - t0) / 60:.1f}} min", flush=True)
    if rc != 0:
        sh(f"tail -n 40 {{log}}")
        sys.exit(rc)
print("ALL_STEPS_DONE", flush=True)
'''

STEPS = ["01_ocr.py", "02_extract_features.py", "03_benchmark.py", "04_robustness.py", "05_explain.py",
         "06_error_analysis.py", "07_report.py", "11_augmentation.py"]


def code_tarball() -> str:
    buf = io.BytesIO()
    with tarfile.open(fileobj=buf, mode="w:gz") as tar:
        for name in INCLUDE:
            p = ROOT / name
            if p.exists():
                tar.add(p, arcname=name, filter=lambda ti: None if "__pycache__" in ti.name else ti)
    return base64.b64encode(buf.getvalue()).decode()


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--dataset", required=True, choices=list(DATA))
    ap.add_argument("--user", required=True, help="Kaggle username that will own the (private) kernel")
    ap.add_argument("--steps", nargs="+", default=STEPS, help="pipeline scripts to run (default: all)")
    ap.add_argument("--suffix", default="", help="kernel slug suffix, e.g. 'aug' -> toonsense-<dataset>-aug")
    ap.add_argument("--reuse-output", action="store_true",
                    help="attach the output of <user>/toonsense-<dataset> and reuse its cached features")
    ap.add_argument("--cpu", action="store_true", help="CPU session (no GPU quota), e.g. for the augmentation step")
    args = ap.parse_args()
    d = DATA[args.dataset]
    slug = f"toonsense-{args.dataset}" + (f"-{args.suffix}" if args.suffix else "")
    out = ROOT / "kaggle" / slug.removeprefix("toonsense-")
    out.mkdir(parents=True, exist_ok=True)
    (out / "run.py").write_text(RUNNER.format(dataset=args.dataset, code=code_tarball(), cmds=d["cmd"], labels=d["labels"],
                                              image_dirs=d["image_dirs"], steps=args.steps,
                                              reuse=args.reuse_output, device="cpu" if args.cpu else "cuda"), encoding="utf-8")
    meta = {
        "id": f"{args.user}/{slug}",
        "title": slug,
        "code_file": "run.py",
        "language": "python",
        "kernel_type": "script",
        "is_private": True,
        "enable_gpu": not args.cpu,
        "enable_tpu": False,
        "enable_internet": True,
        "dataset_sources": d["kaggle_sources"],
        "competition_sources": [],
        "kernel_sources": [f"{args.user}/toonsense-{args.dataset}"] if args.reuse_output else [],
    }
    (out / "kernel-metadata.json").write_text(json.dumps(meta, indent=2), encoding="utf-8")
    kb = (out / "run.py").stat().st_size / 1024
    print(f"wrote {out}/run.py ({kb:.0f} KB) and kernel-metadata.json  ->  kaggle kernels push -p {out.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
